#!/usr/bin/env bash
set -Eeuo pipefail

ROOT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"

grep -Fq 'start_sudo_keepalive' "$ROOT_DIR/install.sh"
grep -Fq 'sudo -n true' "$ROOT_DIR/lib/common.sh"
grep -Fq 'bash "$module_path" </dev/null' "$ROOT_DIR/install.sh"
grep -Fq 'dnf install -y --skip-unavailable' "$ROOT_DIR/lib/common.sh"

grep -Fq 'workstation-setup.jpg' "$ROOT_DIR/dotfiles/sway/.config/sway/config"
grep -Fq 'wpctl set-volume' "$ROOT_DIR/dotfiles/sway/.config/sway/config"
grep -Fq 'set $term kitty' "$ROOT_DIR/dotfiles/sway/.config/sway/config"
grep -Fq 'set $lock $HOME/.local/bin/workstation-lock' "$ROOT_DIR/dotfiles/sway/.config/sway/config"
grep -Fq 'set $menu $HOME/.local/bin/workstation-shell launcher' "$ROOT_DIR/dotfiles/sway/.config/sway/config"
grep -Fq 'bindsym $mod+b splith' "$ROOT_DIR/dotfiles/sway/.config/sway/config"
grep -Fq 'bindsym $mod+v splitv' "$ROOT_DIR/dotfiles/sway/.config/sway/config"
grep -Fq 'bindsym $mod+f fullscreen toggle' "$ROOT_DIR/dotfiles/sway/.config/sway/config"
grep -Fq 'bindsym $mod+g exec $HOME/.local/bin/workstation-shell shortcuts' "$ROOT_DIR/dotfiles/sway/.config/sway/config"
grep -Fq 'app_id="^lxqt-policykit-agent$"' "$ROOT_DIR/dotfiles/sway/.config/sway/config.d/60-policykit-window.conf"
grep -Fq 'resize set width 560 height 300' "$ROOT_DIR/dotfiles/sway/.config/sway/config.d/60-policykit-window.conf"
grep -Fq 'app_id="^org.pulseaudio.pavucontrol$"' "$ROOT_DIR/dotfiles/sway/.config/sway/config.d/61-desktop-app-windows.conf"
grep -Fq 'workstation-(bluetooth|audio|network|storage|system-monitor|system-tool)' "$ROOT_DIR/dotfiles/sway/.config/sway/config.d/62-system-utilities.conf"

grep -Fq 'stow-dotfiles" apply' "$ROOT_DIR/modules/75-sway-desktop.sh"
grep -Fq 'active_theme="$("$HOME/.local/bin/workstation-theme" current)"' "$ROOT_DIR/modules/75-sway-desktop.sh"
grep -Fq 'bash "$ROOT_DIR/modules/26-kitty.sh" </dev/null' "$ROOT_DIR/modules/75-sway-desktop.sh"
grep -Fq 'install_available_packages kitty kitty-terminfo ncurses zsh' "$ROOT_DIR/modules/26-kitty.sh"
grep -Fq 'lxqt-policykit' "$ROOT_DIR/modules/75-sway-desktop.sh"
grep -Fq 'cascadia-mono-nf-fonts' "$ROOT_DIR/modules/75-sway-desktop.sh"
grep -Fq 'NetworkManager-tui' "$ROOT_DIR/modules/75-sway-desktop.sh"
grep -Fq '$HOME/.local/bin/workstation-policykit-agent' "$ROOT_DIR/dotfiles/sway/.config/sway/config"
! grep -Fq 'polkit-gnome' "$ROOT_DIR/modules/75-sway-desktop.sh"
! grep -Fq 'polkit-gnome' "$ROOT_DIR/dotfiles/sway/.config/sway/config"
grep -Fq "timeout 3600 '\$lock'" "$ROOT_DIR/dotfiles/sway/.config/sway/config"
grep -Fq 'xkb_layout it' "$ROOT_DIR/dotfiles/sway/.config/sway/config"
grep -Fq 'gaps inner 8' "$ROOT_DIR/dotfiles/sway/.config/sway/config"
grep -Fq 'gaps outer 0' "$ROOT_DIR/dotfiles/sway/.config/sway/config"

grep -Fq 'HandleLidSwitch=suspend' "$ROOT_DIR/templates/logind-lid.conf"
grep -Fq 'HandleLidSwitchExternalPower=suspend' "$ROOT_DIR/templates/logind-lid.conf"
grep -Fq 'HandleLidSwitchDocked=suspend' "$ROOT_DIR/templates/logind-lid.conf"
grep -Fq '/etc/systemd/logind.conf.d/90-workstation-setup-lid.conf' "$ROOT_DIR/modules/75-sway-desktop.sh"
test -f "$ROOT_DIR/dotfiles/sway/.config/xdg-desktop-portal/sway-portals.conf"
test -x "$ROOT_DIR/bin/workstation-theme"
test -x "$ROOT_DIR/bin/workstation-lock"
test -x "$ROOT_DIR/bin/workstation-network"
test -f "$ROOT_DIR/dotfiles/scripts/.local/bin/workstation-network"
test -x "$ROOT_DIR/bin/workstation-system-tool"
test -f "$ROOT_DIR/dotfiles/scripts/.local/bin/workstation-system-tool"
test -x "$ROOT_DIR/bin/workstation-shell"
test -f "$ROOT_DIR/dotfiles/scripts/.local/bin/workstation-shell"
test -x "$ROOT_DIR/bin/workstation-policykit-agent"
grep -Fq 'QT_QPA_PLATFORMTHEME=gtk3' "$ROOT_DIR/bin/workstation-policykit-agent"
test -f "$ROOT_DIR/dotfiles/scripts/.local/bin/workstation-policykit-agent"
grep -Fq 'include theme.conf' "$ROOT_DIR/dotfiles/kitty/.config/kitty/kitty.conf"

# Native Quickshell Shortcuts
