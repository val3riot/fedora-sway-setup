grep -Fq 'ShortcutsPopup' "$ROOT_DIR/dotfiles/quickshell/.config/quickshell/workstation/desktop/DesktopTools.qml"
grep -Fq 'workstation-shell shortcuts' "$ROOT_DIR/dotfiles/sway/.config/sway/config.d/92-desktop-tools.conf"

# Palette single source of truth
test -f "$ROOT_DIR/config/palette.env"
grep -Fq 'ACCENT_COLOR="#e88923"' "$ROOT_DIR/config/palette.env"
grep -Fq 'BORDER_FOCUSED="#e88923"' "$ROOT_DIR/config/palette.env"

# Absence of legacy files and templates
! test -e "$ROOT_DIR/dotfiles/waybar"
! test -e "$ROOT_DIR/bin/waybar-cpu-temperature"
! test -e "$ROOT_DIR/bin/sway-shortcuts"
! test -e "$ROOT_DIR/bin/sway-help"
! test -e "$ROOT_DIR/bin/workstation-app-menu"
! test -e "$ROOT_DIR/bin/workstation-network-editor"
! test -e "$ROOT_DIR/templates/themes/light"
! test -e "$ROOT_DIR/templates/themes/dark/fuzzel.ini"
! test -e "$ROOT_DIR/templates/themes/dark/mako.conf"
! test -e "$ROOT_DIR/templates/themes/dark/waybar.css"

printf '%s\n' 'OK   configurazione Sway e integrazioni desktop'
